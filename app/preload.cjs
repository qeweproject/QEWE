const {contextBridge,ipcRenderer}=require('electron');
contextBridge.exposeInMainWorld('desktop',{
  ledgerAvailable:true,
  platformInfo:()=>ipcRenderer.invoke('platform-info'),
  transfersAvailable:true,
  offlineMode:enabled=>ipcRenderer.invoke('offline-mode',enabled),
  offlinePrepare:request=>ipcRenderer.invoke('offline-prepare',request),
  offlineRead:text=>ipcRenderer.invoke('offline-read',text),
  offlineStart:request=>ipcRenderer.invoke('offline-start',request),
  offlineComplete:request=>ipcRenderer.invoke('offline-complete',request),
  offlineCancel:request=>ipcRenderer.invoke('offline-cancel',request),
  offlineBroadcast:request=>ipcRenderer.invoke('offline-broadcast',request),
  offlineExport:request=>ipcRenderer.invoke('offline-export',request),
  preferences:()=>ipcRenderer.invoke('preferences'),
  setLanguage:lang=>ipcRenderer.invoke('ui-language',lang),
  tokenSettings:request=>ipcRenderer.invoke('token-settings',request),
  registerLedger:rows=>ipcRenderer.invoke('ledger-register',rows),
  transferAssets:()=>ipcRenderer.invoke('transfer-assets'),
  prepareTransfer:request=>ipcRenderer.invoke('transfer-prepare',request),
  startTransfer:request=>ipcRenderer.invoke('transfer-start',request),
  broadcastTransfer:request=>ipcRenderer.invoke('transfer-broadcast',request),
  transferStatus:request=>ipcRenderer.invoke('transfer-status',request),
  cancelTransfer:request=>ipcRenderer.invoke('transfer-cancel',request),
  openTransaction:hash=>ipcRenderer.invoke('open-transaction',hash),
  beginLedger:()=>ipcRenderer.invoke('ledger-begin'),
  endLedger:()=>ipcRenderer.invoke('ledger-end'),
  scan:request=>ipcRenderer.invoke('scan',request),
  cancel:()=>ipcRenderer.invoke('cancel'),
  forget:()=>ipcRenderer.invoke('forget'),
  copyAddresses:addresses=>ipcRenderer.invoke('copy-addresses',addresses),
  openExplorer:address=>ipcRenderer.invoke('open-explorer',address),
  export:request=>ipcRenderer.invoke('export',request),
  onScan:callback=>ipcRenderer.on('scan-event',(_event,message)=>callback(message))
});
